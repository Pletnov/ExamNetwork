/*
 Фінальне завдання: «Мережевий менеджер завантаження файлів»
 
Опис
Розробіть клієнт-серверний застосунок для віддаленого завантаження файлів з інтернету.
Клієнт надсилає серверу посилання на файл, який необхідно завантажити. Сервер додає завдання до черги та виконує завантаження у фоновому режимі.
Користувач може переглядати список завантажень, перевіряти їхній статус та завантажувати готові файли із сервера на свій комп'ютер.
 
1. Функціонал сервера
Сервер повинен:
приймати підключення від декількох клієнтів одночасно;
приймати від клієнтів посилання на файли для завантаження;
додавати отримані посилання до черги завантажень;
завантажувати файли з черги у фоновому режимі, не блокуючи обробку клієнтських запитів;
зберігати завантажені файли у визначеній папці;
обробляти помилки під час завантаження;
надавати клієнтам список усіх завантажень із поточними статусами;
передавати завантажений файл клієнту за його запитом.
Для кожного завантаження необхідно зберігати:
унікальний ідентифікатор;
посилання на файл;
назву файлу;
дату додавання до черги;
поточний статус;
повідомлення про помилку (якщо вона виникла).
 
Статуси завантаження
Очікує — файл додано до черги, але завантаження ще не розпочалося.
Завантажується — сервер зараз завантажує файл.
Завантажено — файл успішно завантажений і доступний для отримання.
Помилка — під час завантаження виникла помилка.
 
2. Функціонал клієнта
Клієнт повинен надавати користувачу можливість вибрати одну з команд:

1. Додати файл до завантаження
Користувач вводить URL-посилання на файл.
Клієнт надсилає посилання серверу.
Сервер додає нове завдання до черги.
Клієнт отримує підтвердження про додавання.

2. Переглянути список завантажень
Клієнт запитує у сервера список усіх завантажень.
Отримує інформацію про кожен файл та його поточний статус.
Відображає список у зручному для користувача вигляді.

3. Завантажити файл із сервера
Користувач вибирає файл зі списку успішно завантажених.
Клієнт надсилає серверу запит на отримання файлу.
Сервер передає файл через мережеве з'єднання.
Клієнт зберігає файл у локальній папці.
 
3. Приклад сценарію роботи
Користувач запускає клієнтський застосунок.
Підключається до сервера.
Вибирає команду додавання файлу.
Вводить посилання на файл.
Сервер додає завантаження до черги.
Сервер починає завантажувати файл у фоновому режимі.
Користувач може переглядати список завантажень та бачити зміну їхніх статусів.
Після успішного завантаження користувач вибирає файл зі списку.
Сервер передає файл клієнту.
Клієнт зберігає файл на локальному комп'ютері.
 
4. Технічні вимоги
Мова програмування: C#.
Для мережевої взаємодії використовувати TCP.
Сервер повинен підтримувати одночасне підключення декількох клієнтів.
Завантаження файлів з інтернету виконувати за допомогою HttpClient.
Для обробки черги завантажень використовувати окремий потік або Task.
Обробка завантажень не повинна блокувати приймання нових запитів від клієнтів.
Передбачити обробку помилок мережевого з'єднання та недоступних URL.
Передачу файлів між сервером і клієнтом реалізувати через TCP.
 
